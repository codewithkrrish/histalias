"""Write the suggested aliases into the user's shell rc file.

All writes go to our own marked block so we never touch the user's own
lines: applying twice without --force is an error, not a duplicate
append. The rc file is always rewritten atomically (temp file + rename)
and backed up once before the first apply.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

from .analyze import Suggestion

BLOCK_START = "# >>> histalias >>>"
BLOCK_END = "# <<< histalias <<<"


class RcFileError(Exception):
    """Raised when the rc file can't be updated safely."""


def default_rc_file() -> Path:
    shell = os.environ.get("SHELL", "")
    if "zsh" in shell:
        return Path.home() / ".zshrc"
    return Path.home() / ".bashrc"


def render_block(suggestions: list[Suggestion], names: dict[str, str]) -> str:
    """Render the alias definitions as a shell snippet."""
    lines = [BLOCK_START, "# generated by histalias — edit or delete freely"]
    for s in suggestions:
        name = names[s.command]
        # single quotes in the command would break the alias; bail to
        # double quotes only when needed (rare in history)
        quote = '"' if "'" in s.command else "'"
        lines.append(
            f"alias {name}={quote}{s.command}{quote}  "
            f"# used {s.count}x, saves ~{s.count * s.saved_per_use} keystrokes"
        )
    lines.append(BLOCK_END)
    return "\n".join(lines) + "\n"


def apply(rc_path: Path, block: str, force: bool = False) -> Path:
    """Insert (or replace with --force) our block in *rc_path*.

    Returns the backup path created before writing.
    Raises RcFileError when refusing to act.
    """
    original = rc_path.read_text(encoding="utf-8") if rc_path.exists() else ""
    if BLOCK_START in original and not force:
        raise RcFileError(
            f"{rc_path} already has a histalias block — "
            "use --force to replace it, or edit it by hand"
        )

    backup = rc_path.with_name(rc_path.name + ".histalias.bak")
    if rc_path.exists():
        backup.write_bytes(rc_path.read_bytes())

    new_text = _replace_block(original, block) if BLOCK_START in original else _append_block(original, block)
    _atomic_write(rc_path, new_text)
    return backup


def _append_block(original: str, block: str) -> str:
    if original and not original.endswith("\n"):
        original += "\n"
    return original + "\n" + block


def _replace_block(original: str, block: str) -> str:
    start = original.index(BLOCK_START)
    end = original.index(BLOCK_END) + len(BLOCK_END)
    return original[:start] + block + original[end:].lstrip("\n")


def _atomic_write(path: Path, text: str) -> None:
    # write to a temp file in the same directory, then rename —
    # a crash mid-write can't leave a half-written rc file
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".histalias-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
